"""Settings menu translations (gettext, maintained on Weblate).

  translations.py rc OUT        resource script embedding translations/*.po
                                (called by build.cmd; empty without translations)
  translations.py template      rebuild translations/FrankyRenderer.pot from the
                                menu (builds and runs Tools/menu_texts.cpp)

English is the source language and the lookup key. Translators edit
translations/<language>.po on Weblate; the renderer embeds them as "PO"
resources named by language and falls back to English for missing texts.
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRANSLATIONS = ROOT.parent / "translations"
TEMPLATE = TRANSLATIONS / "FrankyRenderer.pot"


def write_rc(out):
    lines = ["// Generated by Tools/translations.py: embedded menu translations."]
    for po in sorted(TRANSLATIONS.glob("*.po")):
        if not po.stem.replace("_", "").replace("@", "").isalnum():
            raise ValueError(f"Unexpected translation file name: {po.name}")
        lines.append(f'{po.stem} PO "{str(po.resolve()).replace(chr(92), chr(92) * 2)}"')
    Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")


def po_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n") + '"'


def unescape(text):
    out, i = [], 0
    while i < len(text):
        if text[i] == "\\" and i + 1 < len(text):
            out.append({"t": "\t", "n": "\n"}.get(text[i + 1], text[i + 1]))
            i += 2
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def write_template():
    work = Path(tempfile.mkdtemp())
    exe, listing = work / "menu_texts.exe", work / "menu_texts.txt"
    build = f"""@echo off
call "{ROOT}\\Tools\\vsenv.cmd" >nul 2>&1
cd /d "{ROOT}"
cl /nologo /utf-8 /std:c++20 /EHsc /O2 /MT /DUNICODE /D_UNICODE /DNOMINMAX /I . /I deps\\msys\\ucrt64\\include ^
 Tools\\menu_texts.cpp UI\\Direct2DSettingsHost.cpp Settings\\Settings.cpp /Fo"{work}\\\\" /Fe"{exe}" ^
 /link build\\lib\\libplacebo.lib d2d1.lib dwrite.lib comdlg32.lib comctl32.lib ole32.lib oleaut32.lib ^
 user32.lib gdi32.lib advapi32.lib shell32.lib shlwapi.lib dwmapi.lib
"""
    (work / "build.cmd").write_text(build, encoding="utf-8")
    result = subprocess.run(["cmd", "/c", str(work / "build.cmd")], capture_output=True, text=True, errors="replace")
    if result.returncode or not exe.exists():
        sys.exit("Building the menu text tool failed:\n" + result.stdout[-3000:])
    subprocess.run([str(exe), str(listing)], check=True, cwd=ROOT / "build" / "bin")
    entries = {}
    for line in listing.read_text(encoding="utf-8").splitlines():
        note, text = (unescape(part) for part in line.split("\t", 1))
        entries.setdefault(text, []).append(note)
    out = [
        "# FrankyRenderer settings menu.",
        "# This file is generated by src/Tools/translations.py template; edit the",
        "# translations in translations/<language>.po (Weblate).",
        "#",
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: FrankyRenderer\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        "",
    ]
    for text, notes in entries.items():
        for note in dict.fromkeys(notes[:3]):
            out.append("#. " + note.replace("\n", " "))
        out.append("msgid " + po_string(text))
        out.append('msgstr ""')
        out.append("")
    TRANSLATIONS.mkdir(exist_ok=True)
    TEMPLATE.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{TEMPLATE.relative_to(ROOT.parent)}: {len(entries)} texts")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("rc").add_argument("out")
    commands.add_parser("template")
    args = parser.parse_args()
    if args.command == "rc":
        write_rc(args.out)
    else:
        write_template()


if __name__ == "__main__":
    main()
